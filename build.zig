const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    const tables: Tables = .{
        .entity = generate(b, "gen_entities", &.{"data/entities.json"}, "entity_table.zig"),
        .unicode = generate(b, "gen_unicode", &.{
            "data/DerivedGeneralCategory.txt",
            "data/CaseFolding.txt",
        }, "unicode_table.zig"),
    };
    const md = mdModule(b, target, optimize, tables);

    const mod = b.createModule(.{
        .root_source_file = b.path("src/main.zig"),
        .target = target,
        .optimize = optimize,
    });

    const options = b.addOptions();
    options.addOption([]const u8, "version", @import("build.zig.zon").version);
    mod.addOptions("build_options", options);
    mod.addImport("md", md);
    mod.addImport("width_table", generate(b, "gen_width", &.{
        "data/EastAsianWidth.txt",
        "data/emoji-data.txt",
        "data/DerivedGeneralCategory.txt",
    }, "width_table.zig"));

    const exe = b.addExecutable(.{
        .name = "mdv",
        .root_module = mod,
    });
    b.installArtifact(exe);

    const run = b.addRunArtifact(exe);
    run.step.dependOn(b.getInstallStep());
    run.addPassthruArgs();
    b.step("run", "Run mdv").dependOn(&run.step);

    const spec = b.addExecutable(.{
        .name = "spec",
        .root_module = b.createModule(.{
            .root_source_file = b.path("test/spec.zig"),
            .target = target,
            .optimize = optimize,
            .imports = &.{.{ .name = "md", .module = md }},
        }),
    });
    const spec_run = b.addRunArtifact(spec);
    spec_run.addFileArg(b.path("test/spec/spec.json"));
    spec_run.addFileArg(b.path("test/spec/gfm.txt"));
    spec_run.addPassthruArgs();
    b.step("spec", "Run the CommonMark and GFM extension examples").dependOn(&spec_run.step);

    // Timed, so always optimized.
    const pathological = b.addExecutable(.{
        .name = "pathological",
        .root_module = b.createModule(.{
            .root_source_file = b.path("test/pathological.zig"),
            .target = target,
            .optimize = .ReleaseFast,
            .imports = &.{.{ .name = "md", .module = mdModule(b, target, .ReleaseFast, tables) }},
        }),
    });
    const pathological_run = b.addRunArtifact(pathological);
    pathological_run.addPassthruArgs();
    b.step("pathological", "Run cmark's pathological inputs").dependOn(&pathological_run.step);

    const test_step = b.step("test", "Run the tests");
    test_step.dependOn(&b.addRunArtifact(b.addTest(.{ .root_module = mod })).step);
    test_step.dependOn(&b.addRunArtifact(b.addTest(.{ .root_module = md })).step);
}

const Tables = struct { entity: *std.Build.Module, unicode: *std.Build.Module };

/// The markdown library, `src/md/`.
fn mdModule(b: *std.Build, target: std.Build.ResolvedTarget, optimize: std.builtin.OptimizeMode, tables: Tables) *std.Build.Module {
    const md = b.createModule(.{
        .root_source_file = b.path("src/md/root.zig"),
        .target = target,
        .optimize = optimize,
    });
    md.addImport("entity_table", tables.entity);
    md.addImport("unicode_table", tables.unicode);
    return md;
}

/// A module generated by `build/<generator>.zig`, run on the host with the
/// given data files.
fn generate(b: *std.Build, generator: []const u8, inputs: []const []const u8, output: []const u8) *std.Build.Module {
    const exe = b.addExecutable(.{
        .name = generator,
        .root_module = b.createModule(.{
            .root_source_file = b.path(b.fmt("build/{s}.zig", .{generator})),
            .target = b.graph.host,
        }),
    });
    const run = b.addRunArtifact(exe);
    for (inputs) |input| run.addFileArg(b.path(input));
    return b.createModule(.{ .root_source_file = run.addOutputFileArg(output) });
}
