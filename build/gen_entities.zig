//! Generates the table of HTML named character references from the WHATWG
//! `entities.json`: names without `&` and `;`, sorted bytewise, and their
//! UTF-8. Names without the closing `;` are legacy forms CommonMark ignores.
//!
//! usage: gen_entities ENTITIES_JSON OUT_ZIG

const std = @import("std");

const Entity = struct { name: []const u8, value: []const u8 };

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) return error.Usage;

    const json = try std.Io.Dir.cwd().readFileAlloc(io, args[1], arena, .unlimited);
    const root = try std.json.parseFromSliceLeaky(std.json.Value, arena, json, .{});

    var entities: std.ArrayList(Entity) = .empty;
    var it = root.object.iterator();
    while (it.next()) |entry| {
        const key = entry.key_ptr.*;
        if (!std.mem.endsWith(u8, key, ";")) continue;
        try entities.append(arena, .{
            .name = key[1 .. key.len - 1],
            .value = entry.value_ptr.object.get("characters").?.string,
        });
    }
    std.mem.sort(Entity, entities.items, {}, struct {
        fn lessThan(_: void, a: Entity, b: Entity) bool {
            return std.mem.lessThan(u8, a.name, b.name);
        }
    }.lessThan);

    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll("//! Generated by build/gen_entities.zig from data/entities.json.\n\n");
    try w.writeAll("pub const names = [_][]const u8{\n");
    for (entities.items) |e| try w.print("    \"{f}\",\n", .{std.zig.fmtString(e.name)});
    try w.writeAll("};\n\npub const values = [_][]const u8{\n");
    for (entities.items) |e| try w.print("    \"{f}\",\n", .{std.zig.fmtString(e.value)});
    try w.writeAll("};\n");

    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = args[2], .data = out.written() });
}
