//! Generates the Unicode tables inline parsing needs from the character
//! database: punctuation (general categories P and S, as CommonMark 0.31.2
//! defines it) and space separators (Zs) as sorted, merged code point
//! ranges, and full case folding (statuses C and F) as sorted code points
//! with their folded UTF-8.
//!
//! usage: gen_unicode DERIVED_GENERAL_CATEGORY CASE_FOLDING OUT_ZIG

const std = @import("std");

const Range = [2]u21;
const Fold = struct { from: u21, to: []const u8 };

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 4) return error.Usage;
    const cwd = std.Io.Dir.cwd();

    var punctuation: std.ArrayList(Range) = .empty;
    var space: std.ArrayList(Range) = .empty;
    var lines = std.mem.splitScalar(u8, try cwd.readFileAlloc(io, args[1], arena, .unlimited), '\n');
    while (lines.next()) |line| {
        var fields = recordFields(line) orelse continue;
        const range = try parseRange(fields.next().?);
        const category = std.mem.trim(u8, fields.next().?, " ");
        if (category[0] == 'P' or category[0] == 'S') try punctuation.append(arena, range);
        if (std.mem.eql(u8, category, "Zs")) try space.append(arena, range);
    }

    var folds: std.ArrayList(Fold) = .empty;
    lines = std.mem.splitScalar(u8, try cwd.readFileAlloc(io, args[2], arena, .unlimited), '\n');
    while (lines.next()) |line| {
        var fields = recordFields(line) orelse continue;
        const from = try parseCode(fields.next().?);
        const status = std.mem.trim(u8, fields.next().?, " ");
        if (!std.mem.eql(u8, status, "C") and !std.mem.eql(u8, status, "F")) continue;
        var to: std.ArrayList(u8) = .empty;
        var codes = std.mem.tokenizeScalar(u8, fields.next().?, ' ');
        while (codes.next()) |code| {
            var buf: [4]u8 = undefined;
            const len = try std.unicode.utf8Encode(try parseCode(code), &buf);
            try to.appendSlice(arena, buf[0..len]);
        }
        try folds.append(arena, .{ .from = from, .to = to.items });
    }
    std.mem.sort(Fold, folds.items, {}, struct {
        fn lessThan(_: void, a: Fold, b: Fold) bool {
            return a.from < b.from;
        }
    }.lessThan);

    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll("//! Generated by build/gen_unicode.zig from data/DerivedGeneralCategory.txt\n");
    try w.writeAll("//! and data/CaseFolding.txt (Unicode 17.0.0).\n\n");
    try writeRanges(w, "punctuation", merge(punctuation.items));
    try writeRanges(w, "space", merge(space.items));
    try w.writeAll("pub const fold_keys = [_]u21{\n");
    for (folds.items) |f| try w.print("    0x{X},\n", .{f.from});
    try w.writeAll("};\n\npub const fold_values = [_][]const u8{\n");
    for (folds.items) |f| try w.print("    \"{f}\",\n", .{std.zig.fmtString(f.to)});
    try w.writeAll("};\n");

    try cwd.writeFile(io, .{ .sub_path = args[3], .data = out.written() });
}

/// The `;`-separated fields of a data line, or null for blank and comment lines.
fn recordFields(line: []const u8) ?std.mem.SplitIterator(u8, .scalar) {
    const data = std.mem.trim(u8, line[0 .. std.mem.indexOfScalar(u8, line, '#') orelse line.len], " \t\r");
    if (data.len == 0) return null;
    return std.mem.splitScalar(u8, data, ';');
}

fn parseCode(text: []const u8) !u21 {
    return std.fmt.parseInt(u21, std.mem.trim(u8, text, " "), 16);
}

fn parseRange(text: []const u8) !Range {
    const field = std.mem.trim(u8, text, " ");
    if (std.mem.indexOf(u8, field, "..")) |dots|
        return .{ try parseCode(field[0..dots]), try parseCode(field[dots + 2 ..]) };
    const code = try parseCode(field);
    return .{ code, code };
}

/// Sorts the ranges and joins those that touch or overlap, in place.
fn merge(ranges: []Range) []Range {
    std.mem.sort(Range, ranges, {}, struct {
        fn lessThan(_: void, a: Range, b: Range) bool {
            return a[0] < b[0];
        }
    }.lessThan);
    var len: usize = 0;
    for (ranges) |r| {
        if (len > 0 and r[0] <= ranges[len - 1][1] + 1) {
            ranges[len - 1][1] = @max(ranges[len - 1][1], r[1]);
        } else {
            ranges[len] = r;
            len += 1;
        }
    }
    return ranges[0..len];
}

fn writeRanges(w: *std.Io.Writer, name: []const u8, ranges: []const Range) !void {
    try w.print("pub const {s} = [_][2]u21{{\n", .{name});
    for (ranges) |r| try w.print("    .{{ 0x{X}, 0x{X} }},\n", .{ r[0], r[1] });
    try w.writeAll("};\n\n");
}
