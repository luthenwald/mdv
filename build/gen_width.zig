//! Generates the display width tables from the character database: code
//! points that take two columns (East Asian Wide and Fullwidth, and emoji
//! shown as emoji by default) and code points that take none (combining
//! marks, format characters other than the soft hyphen, and the medial and
//! final Hangul jamo), as sorted, merged code point ranges.
//!
//! usage: gen_width EAST_ASIAN_WIDTH EMOJI_DATA DERIVED_GENERAL_CATEGORY OUT_ZIG

const std = @import("std");
const ucd = @import("ucd.zig");
const Range = ucd.Range;

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 5) return error.Usage;
    const cwd = std.Io.Dir.cwd();

    var wide: std.ArrayList(Range) = .empty;
    var zero: std.ArrayList(Range) = .empty;

    var lines = std.mem.splitScalar(u8, try cwd.readFileAlloc(io, args[1], arena, .unlimited), '\n');
    while (lines.next()) |line| {
        var fields = ucd.recordFields(line) orelse continue;
        const range = try ucd.parseRange(fields.next().?);
        const width = std.mem.trim(u8, fields.next().?, " ");
        if (std.mem.eql(u8, width, "W") or std.mem.eql(u8, width, "F")) try wide.append(arena, range);
    }

    lines = std.mem.splitScalar(u8, try cwd.readFileAlloc(io, args[2], arena, .unlimited), '\n');
    while (lines.next()) |line| {
        var fields = ucd.recordFields(line) orelse continue;
        const range = try ucd.parseRange(fields.next().?);
        if (std.mem.eql(u8, std.mem.trim(u8, fields.next().?, " "), "Emoji_Presentation")) try wide.append(arena, range);
    }

    lines = std.mem.splitScalar(u8, try cwd.readFileAlloc(io, args[3], arena, .unlimited), '\n');
    while (lines.next()) |line| {
        var fields = ucd.recordFields(line) orelse continue;
        const range = try ucd.parseRange(fields.next().?);
        const category = std.mem.trim(u8, fields.next().?, " ");
        if (std.mem.eql(u8, category, "Mn") or std.mem.eql(u8, category, "Me")) {
            try zero.append(arena, range);
        } else if (std.mem.eql(u8, category, "Cf")) {
            // The soft hyphen shows as a hyphen where a terminal shows it at all.
            if (range[0] <= 0xAD and 0xAD <= range[1]) {
                if (range[0] < 0xAD) try zero.append(arena, .{ range[0], 0xAC });
                if (range[1] > 0xAD) try zero.append(arena, .{ 0xAE, range[1] });
            } else try zero.append(arena, range);
        }
    }
    try zero.append(arena, .{ 0x1160, 0x11FF });

    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll("//! Generated by build/gen_width.zig from data/EastAsianWidth.txt,\n");
    try w.writeAll("//! data/emoji-data.txt and data/DerivedGeneralCategory.txt (Unicode 17.0.0).\n\n");
    try ucd.writeRanges(w, "wide", ucd.merge(wide.items));
    try ucd.writeRanges(w, "zero", ucd.merge(zero.items));
    try cwd.writeFile(io, .{ .sub_path = args[4], .data = out.written() });
}
